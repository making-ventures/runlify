export type ConfigValue<T extends FieldType> = T extends 'string'
    ?
      string
    :
      T extends 'int' | 'float'
      ?
        number
      :
        T extends 'bigint'
        ?
          bigint
        :
          T extends 'bool'
          ?
            boolean
          :
            Date

export interface ConfigVar<T extends FieldType = 'string'> {
  name: string
  type: T,
  required: boolean,
  default: ConfigValue<T>
  needFor: string
  scopes: ConfigVarScope[]
}

