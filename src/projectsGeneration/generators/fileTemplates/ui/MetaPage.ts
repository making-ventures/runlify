export const uiMetaPageTmpl = () => {
  return `import React, {FC} from 'react';
import {
  gql,
  useQuery,
} from '@apollo/client';
import {Box, type SxProps, type Theme} from '@mui/material';

const sectionSx: SxProps<Theme> = {
  margin: '10px auto',
};

const catalogSx: SxProps<Theme> = {
  margin: '20px 10px',
};

const fieldSx: SxProps<Theme> = {
  margin: '20px 10px',
};

const META_REQUEST = gql\`
  query {
    Meta
  }
\`;

const MetaPage: FC = () => {
  const {data: result} = useQuery(META_REQUEST);

  return (
    <>
      {result && <div>
        <Box sx={sectionSx}>
          name: {result.Meta.name}
        </Box>
        <Box sx={sectionSx}>
          prefix: {result.Meta.prefix}
        </Box>
        <Box sx={sectionSx}>
          needFor: {result.Meta.needFor}
        </Box>
        <Box sx={sectionSx}>
          deployEnvironments: {result.Meta.deployEnvironments.join(',')}
        </Box>
        <Box sx={sectionSx}>
          configVars: {result.Meta.configVars.join(',')}
        </Box>
        <Box sx={sectionSx}>
          Catalogs:
        </Box>
        <Box sx={sectionSx}>
          {result.Meta.catalogs.map(
            (catalog: any, index: number) => <Catalog catalog={catalog} key={index} />,
          )}
        </Box>
      </div>}
    </>
  );
};

const Catalog: FC<{catalog: any}> = ({catalog}) => {
  return (
    <Box sx={catalogSx}>
      <Box sx={sectionSx}>
        name: {catalog.name}
      </Box>
      <Box sx={sectionSx}>
        needFor: {catalog.needFor}
      </Box>
      <Box sx={sectionSx}>
        Fields:
      </Box>
      <Box sx={sectionSx}>
        {catalog.fields.map(
          (field: any, index: number) => <Field field={field} key={index} />,
        )}
      </Box>
    </Box>
  );
};

const Field: FC<{field: any}> = ({field}) => {
  return (
    <Box sx={fieldSx}>
      <Box sx={sectionSx}>
        name: {field.name}
      </Box>
      <Box sx={sectionSx}>
        type: {field.type}
      </Box>
      <Box sx={sectionSx}>
        required: {field.required?.toString()}
      </Box>
      <Box sx={sectionSx}>
        needFor: {field.needFor}
      </Box>
      <Box sx={sectionSx}>
        requiredOnInput: {field.requiredOnInput?.toString()}
      </Box>
      <Box sx={sectionSx}>
        updatable: {field.updatable?.toString()}
      </Box>
      <Box sx={sectionSx}>
        autoGenerated: {field.autoGenerated?.toString()}
      </Box>
      <Box sx={sectionSx}>
        category: {field.category}
      </Box>
    </Box>
  );
};

export default MetaPage;
`
}
